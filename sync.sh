#!/bin/sh
# Copy the live desktop configuration into this repository.
#
# Layout note: colour is generated. ~/.config/theme/palette.toml is the single
# source of truth and `theme-apply` renders every *colors* file listed under
# GENERATED below. Those are committed anyway so a fresh clone works before
# theme-apply has ever been run -- hyprland.lua does require("theme"), and
# Hyprland will not start if hypr/theme.lua is absent.
set -eu
repo_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
config_dir=${XDG_CONFIG_HOME:-$HOME/.config}
data_dir=${XDG_DATA_HOME:-$HOME/.local/share}

set -- \
    `# ---- compositor + session ----` \
    hypr/hyprland.lua \
    hypr/hyprlock.conf \
    hypr/start-panel.sh \
    hypr/start-wallpaper.sh \
    hypr/start-portals.sh \
    hypr/connections.py \
    hypr/launch-apidog.sh \
    hypr/power-menu.sh \
    hypr/screenshot.sh \
    hypr/lock.sh \
    hypr/hypridle.conf \
    \
    `# ---- theme system (SOURCE of truth) ----` \
    theme/palette.toml \
    theme/palette-akane.toml \
    theme/palette-kanagawa.toml \
    theme/palette-catppuccin-mocha.toml \
    theme/theme-apply \
    theme/README.md \
    \
    `# ---- GENERATED by theme-apply ----` \
    hypr/theme.lua \
    hypr/theme-colors.conf \
    hypr/theme-wallpaper \
    waybar/colors.css \
    swaync/colors.css \
    fuzzel/colors.ini \
    kitty/current-theme.conf \
    wezterm/colors/palette.toml \
    gtk-3.0/colors.css \
    gtk-4.0/colors.css \
    \
    `# ---- panel + launcher + notifications ----` \
    waybar/config.jsonc \
    waybar/style.css \
    waybar/workspace-status.py \
    fuzzel/fuzzel.ini \
    swaync/config.json \
    swaync/style.css \
    \
    `# ---- terminals ----` \
    wezterm/wezterm.lua \
    kitty/kitty.conf \
    \
    `# ---- toolkit theming (GTK + Qt/KDE + portals) ----` \
    gtk-3.0/settings.ini \
    gtk-3.0/gtk.css \
    gtk-4.0/settings.ini \
    gtk-4.0/gtk.css \
    kdeglobals \
    xdg-desktop-portal/hyprland-portals.conf \
    \
    `# ---- wallpapers ----` \
    hypr/wallpapers/orbital-ring.png \
    hypr/wallpapers/material-you.jpg \
    hypr/wallpapers/lavender-dunes.svg \
    hypr/wallpapers/lavender-dunes.png \
    hypr/wallpapers/2-akane.jpg \
    hypr/wallpapers/4-akane.jpg \
    hypr/wallpapers/arc-blueberry-2.png \
    \
    `# ---- systemd user units ----` \
    systemd/user/hypr-wallpaper.service \
    systemd/user/hyprland-session.target

missing=0
for relative in "$@"
do
    if [ ! -f "$config_dir/$relative" ]; then
        printf 'Missing configuration: %s\n' "$config_dir/$relative" >&2
        missing=1
    fi
done
[ "$missing" -eq 0 ] || exit 1

apidog_desktop="$data_dir/applications/apidog.desktop"
if [ ! -f "$apidog_desktop" ]; then
    printf 'Missing application launcher: %s\n' "$apidog_desktop" >&2
    exit 1
fi

for relative in "$@"
do
    mkdir -p "$repo_dir/.config/$(dirname -- "$relative")"
    cp -p -- "$config_dir/$relative" "$repo_dir/.config/$relative"
done

mkdir -p "$repo_dir/.local/share/applications"
cp -p -- "$apidog_desktop" "$repo_dir/.local/share/applications/apidog.desktop"

# KDE colour schemes are generated by theme-apply but live outside .config.
# Only copy the ones our own palettes produce -- a bare glob would also sweep
# in unrelated schemes left behind by previously installed themes.
mkdir -p "$repo_dir/.local/share/color-schemes"
for palette in "$config_dir"/theme/palette*.toml
do
    [ -f "$palette" ] || continue
    name=$(sed -n 's/^name *= *"\(.*\)"$/\1/p' "$palette" | head -1 | tr -d ' ')
    [ -n "$name" ] || continue
    scheme="$data_dir/color-schemes/$name.colors"
    [ -f "$scheme" ] && cp -p -- "$scheme" "$repo_dir/.local/share/color-schemes/"
done

printf 'Copied %s configuration files into %s\n' "$#" "$repo_dir"
